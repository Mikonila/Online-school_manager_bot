# Функция для поиска курса по названию
def find_course_by_name(course_name: str) -> dict:
    """
    Ищет курс по названию (русскому или английскому)
    Возвращает словарь с информацией о курсе или None
    """
    if not course_name:
        return None
    
    # Приводим к нижнему регистру и убираем лишние пробелы
    course_name = course_name.lower().strip()
    
    # Сначала проверяем точное совпадение в mapping
    if course_name in COURSE_NAME_MAPPING:
        course_key = COURSE_NAME_MAPPING[course_name]
        return COURSE_LINKS_DICT.get(course_key)
    
    # Проверяем прямое совпадение в словаре курсов
    if course_name in COURSE_LINKS_DICT:
        return COURSE_LINKS_DICT[course_name]
    
    # Ищем частичные совпадения
    for key, mapping in COURSE_NAME_MAPPING.items():
        if course_name in key or key in course_name:
            course_key = mapping
            return COURSE_LINKS_DICT.get(course_key)
    
    # Ищем в названиях курсов
    for key, course_info in COURSE_LINKS_DICT.items():
        if course_name in course_info["title"].lower():
            return course_info
    
    return None

# Функция для получения ссылки на сайт курса
def get_course_site_link(course_name: str) -> str:
    """
    Возвращает ссылку на сайт курса по названию
    """
    course_info = find_course_by_name(course_name)
    if course_info and course_info.get("site"):
        return course_info["site"]
    return None

